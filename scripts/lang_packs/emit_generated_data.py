"""Write generated Assist packs as YAML data files (package 6.9).

The engine still links the compiled Rust packs. The YAML under `packs/generated/`
is the data form of each generated locale — inspect and diff here instead of the
Rust sources. Phrase corrections that should ship belong in `packs/assist/`, which
touches one file and is never overwritten by this emitter.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from lang_packs.emit_rust import unique_verbs
from lang_packs.fold import fold_latin

ROOT = Path(__file__).resolve().parents[2]
GENERATED = ROOT / "packs" / "generated"
HANDWRITTEN = {"de", "en"}
BANNER = "# @generated by scripts/lang_packs. DO NOT EDIT.\n# Phrase fixes go in packs/assist/{code}.yaml (one file).\n"


def _str_pairs(rows: list) -> list[list[str]]:
    out: list[list[str]] = []
    for row in rows or []:
        if isinstance(row, (list, tuple)) and len(row) >= 2:
            left, right = str(row[0]), str(row[1])
            if left and right:
                out.append([left, right])
    return out


def pack_payload(lang: dict) -> dict:
    """Compact data view of a generated pack — enough to correct a phrase."""
    verbs = [[word, kind] for word, kind in unique_verbs(lang.get("verbs") or [])]
    talk = {key: list(vals) for key, vals in (lang.get("talk") or {}).items()}
    nouns = {key: list(vals) for key, vals in (lang.get("nouns") or {}).items()}
    speech = dict(lang.get("speech") or {})
    for key in ("states", "room_names", "personality"):
        if key in speech and not isinstance(speech[key], (str, int, float, bool, type(None))):
            speech[key] = _str_pairs(speech[key]) if key != "personality" else [
                [name, list(variants)] for name, variants in speech[key]
            ]
    numbers = []
    for word, num in (lang.get("maps") or {}).get("numbers") or []:
        folded = fold_latin(str(word))
        if folded:
            numbers.append([folded, int(num)])
    return {
        "klar_assist_data": "1",
        "id": lang["code"],
        "bcp47": list(lang.get("variants") or [lang["code"]]),
        "extends": lang.get("parent") or lang["code"],
        "native": lang.get("native"),
        "script": lang.get("script", "Latn"),
        "verbs": verbs,
        "talk": talk,
        "nouns": nouns,
        "speech": speech,
        "numbers": numbers,
        "answers": dict(lang.get("answers") or {}),
        "household": {
            key: val
            for key, val in (lang.get("household") or {}).items()
            if key in ("teach", "explain", "undo", "clock", "date", "weekday", "today", "weather")
        },
    }


class LineBreakDumper(yaml.SafeDumper):
    pass


def represent_str(dumper: yaml.SafeDumper, data: str):
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


LineBreakDumper.add_representer(str, represent_str)


def write_generated_data(lang: dict) -> None:
    if lang["code"] in HANDWRITTEN:
        return
    GENERATED.mkdir(parents=True, exist_ok=True)
    path = GENERATED / f"{lang['code']}.yaml"
    payload = pack_payload(lang)
    body = yaml.dump(payload, Dumper=LineBreakDumper, allow_unicode=True, sort_keys=False, width=100)
    path.write_text(BANNER + body, encoding="utf-8")
