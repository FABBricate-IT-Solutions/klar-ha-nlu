def drop_english_spoken(colors: list[tuple[str, str]]) -> list[tuple[str, str]]:
    return [(word, canon) for word, canon in colors if word.casefold() not in EN_COLOR_WORDS]


def colors_for(code: str, existing: list[tuple[str, str]] | None) -> list[tuple[str, str]] | None:
    """Prefer an explicit native table; otherwise strip English spoken keys."""
    if code in NATIVE:
        return list(NATIVE[code])
    if not existing:
        return None
    cleaned = drop_english_spoken(existing)
    return cleaned or None
