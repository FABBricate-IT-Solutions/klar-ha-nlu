"""On/off minimal pairs per locale: the sentences that decide a locale's tier.

`tests/language_tiers.rs` runs them. A locale is stable when every "on" sentence switches
on, every "off" sentence switches off, and neither a question nor a negated command
switches anything. The pairs of a generated pack come from its own lexicon: its smoke
sentences, and the first on and off verb with the same lamp in the same room.
"""

from __future__ import annotations

import json
from pathlib import Path

PATH = Path(__file__).resolve().parents[2] / "tests" / "datasets" / "minimal_pairs" / "pairs.yaml"

# The hand-written packs have no generator lexicon; their pairs are written here.
HAND = {
    "de": {
        "on": ["schalte das licht im wohnzimmer ein", "mach das licht im wohnzimmer an", "licht wohnzimmer an"],
        "off": ["schalte das licht im wohnzimmer aus", "mach das licht im wohnzimmer aus", "licht wohnzimmer aus"],
    },
    "en": {
        "on": ["turn on the living room light", "switch the living room light on", "living room light on"],
        "off": ["turn off the living room light", "switch the living room light off", "living room light off"],
    },
}

def _unique(rows: list[str]) -> list[str]:
    return list(dict.fromkeys(row for row in rows if row))


def pairs_of(core: dict, lang: dict) -> dict:
    said = {intent: text for text, intent in reversed(lang["smoke"])}
    if core.get("parent"):
        # A regional pack holds regional words only: its own pair is its smoke pair, and it
        # must also get the pairs of its parent right.
        return {"on": [said["HassTurnOn"]], "off": [said["HassTurnOff"]], "also": core["parent"]}
    words = core["w"]
    living = next(native for native, canon in core["rooms"] if canon == "wohnzimmer")
    lamp = words["light"][0]
    return {
        "on": _unique([said["HassTurnOn"], f"{words['on'][0]} {lamp} {living}"]),
        "off": _unique([said["HassTurnOff"], f"{words['off'][0]} {lamp} {living}"]),
    }


def write_pairs(cores: list[dict], generated: list[dict]) -> None:
    rows = dict(HAND)
    for core, lang in zip(cores, generated):
        rows[core["code"]] = pairs_of(core, lang)
    lines = [
        "# @generated by scripts/lang_packs. DO NOT EDIT.",
        "# On/off minimal pairs per locale (scripts/lang_packs/pairs.py). tests/language_tiers.rs",
        "# runs them and decides which locales are stable.",
    ]
    lines += [f"{json.dumps(code)}: {json.dumps(row, ensure_ascii=False)}" for code, row in rows.items()]
    PATH.parent.mkdir(parents=True, exist_ok=True)
    PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
