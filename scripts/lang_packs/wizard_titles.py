def _expand(chrome: str, units: str, rest: str, tutorial: str) -> dict[str, str]:
    # Titles are localized; supporting leads stay on the English oracle until a later pack pass.
    return {
        "chromeTitle": chrome,
        "chromeLead": _EN_LEADS["chromeLead"],
        "unitsTitle": units,
        "unitsLead": _EN_LEADS["unitsLead"],
        "restTitle": rest,
        "restLead": _EN_LEADS["restLead"],
        "tutorialTitle": tutorial,
        "llmSkip": _EN_LEADS["llmSkip"],
    }


for _code, (_c, _u, _r, _t) in _MORE.items():
    TITLES[_code] = _expand(_c, _u, _r, _t)


# Prefer short native leads where we already authored full packs above.
for _code in list(TITLES):
    row = TITLES[_code]
    for key in ("chromeTitle", "unitsTitle", "restTitle", "tutorialTitle", "chromeLead", "unitsLead", "restLead", "llmSkip"):
        if key not in row:
            raise SystemExit(f"wizard_titles {_code} missing {key}")
