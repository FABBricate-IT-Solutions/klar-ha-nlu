/// Contextual verb class. The engine maps these to `Action`; packs only classify words.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum VerbKind {
    On,
    OnParticle,
    Off,
    Open,
    /// German *öffnen*: door/lock words win over cover.
    OpenDoor,
    Close,
    Up,
    Down,
    Roll,
    Lower,
    Auf,
    Stop,
    Toggle,
    Dim,
    Brightness,
    Speed,
    Climate,
    Temperature,
    Query,
    Switch,
    Pause,
    Playback,
    Play,
    Next,
    Mute,
    FanNoun,
    Vacuum,
    Dock,
    Scene,
    VacuumNoun,
    Lock,
    LockNoun,
    CloseLock,
    Unlock,
    Set,
    Position,
    Flick,
    ClarifyWrong,
    Timer,
    List,
    Add,
    ListComplete,
    Make,
    Color,
    Percent,
}

