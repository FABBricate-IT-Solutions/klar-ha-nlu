//! `export_typescript` writes `web/src/generated/contract.ts`. CI runs the exporter
//! through `scripts/check_generated.sh` and fails when the committed file drifts.
//! Exhaustive matches below turn a new Rust enum variant into a compile error until
//! the list (and then the generated TypeScript) is updated.

