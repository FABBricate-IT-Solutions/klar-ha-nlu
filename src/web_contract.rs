/// TypeScript module for the operator UI. Keep in sync by running the exporter binary.
pub fn export_typescript() -> String {
    let mut out = String::new();
    out.push_str("// @generated by cargo run --bin export_web_contract. DO NOT EDIT.\n");
    out.push_str("// Source of truth: src/web_contract.rs (exhaustive against Rust enums).\n\n");
    writeln!(out, "export const PARSE_SCHEMA_VERSION = \"{PARSE_SCHEMA_VERSION}\";").unwrap();
    writeln!(out, "export const MAX_PARSE_CHARS = {MAX_PARSE_CHARS};").unwrap();
    writeln!(out, "export const MAX_PLAN_STEPS = {MAX_PLAN_STEPS};").unwrap();
    writeln!(out, "export const MAX_CANDIDATES = {MAX_CANDIDATES};").unwrap();
    writeln!(out, "export const MAX_EVIDENCE = {MAX_EVIDENCE};").unwrap();
    writeln!(out, "export const MAX_EVIDENCE_PER_ITEM = {MAX_EVIDENCE_PER_ITEM};").unwrap();
    writeln!(out, "export const MAX_CLARIFY_OPTIONS = {MAX_CLARIFY_OPTIONS};").unwrap();
    writeln!(out, "export const MAX_TRACE_STAGES = {MAX_TRACE_STAGES};").unwrap();
    writeln!(out, "export const MAX_TRACE_DISCARDED = {MAX_TRACE_DISCARDED};").unwrap();
    writeln!(out, "export const MAX_DETAIL_CHARS = {MAX_DETAIL_CHARS};").unwrap();
    writeln!(out, "export const MAX_TRACE_TOKENS = {MAX_TRACE_TOKENS};").unwrap();
    writeln!(out, "export const MAX_TRACE_TOKEN_CHARS = {MAX_TRACE_TOKEN_CHARS};").unwrap();
    out.push('\n');
    write_const_list(&mut out, "POLICY_EFFECTS", policy_effects());
    write_const_list(&mut out, "REFINE_BANDS", refine_bands());
    write_const_list(&mut out, "REJECT_REASONS", reject_reasons());
    write_const_list(&mut out, "PERSONALITIES", personalities());
    write_const_list(&mut out, "MODES", modes());
    write_const_list(&mut out, "UNIT_SYSTEMS", unit_systems());
    write_const_list(&mut out, "LANGUAGE_TIERS", language_tiers());
    write_const_list(&mut out, "PARSE_DECISIONS", parse_decisions());
    write_const_list(&mut out, "CHAT_EVENT_TYPES", chat_event_types());
    write_const_list(&mut out, "PARSE_OUTCOME_FIELDS", parse_outcome_fields());
    write_const_list(&mut out, "PARSE_OUTCOME_OPTIONAL_FIELDS", parse_outcome_optional_fields());
    write_const_list(&mut out, "SETTINGS_FIELDS", settings_fields());
    out.push('\n');
    out.push_str("export type PolicyEffect = (typeof POLICY_EFFECTS)[number];\n");
    out.push_str("export type RefineBand = (typeof REFINE_BANDS)[number];\n");
    out.push_str("export type RejectReason = (typeof REJECT_REASONS)[number];\n");
    out.push_str("export type PersonalityId = (typeof PERSONALITIES)[number];\n");
    out.push_str("export type Mode = (typeof MODES)[number];\n");
    out.push_str("export type UnitSystem = (typeof UNIT_SYSTEMS)[number];\n");
    out.push_str("export type LanguageTier = (typeof LANGUAGE_TIERS)[number];\n");
    out.push_str("export type ParseDecisionType = (typeof PARSE_DECISIONS)[number];\n");
    out.push_str("export type ChatEventType = (typeof CHAT_EVENT_TYPES)[number];\n");
    out
}

fn write_const_list(out: &mut String, name: &str, values: &[&str]) {
    writeln!(out, "export const {name} = [").unwrap();
    for value in values {
        writeln!(out, "  \"{value}\",").unwrap();
    }
    out.push_str("] as const;\n\n");
}

fn assert_listed(name: &str, wire: &str, listed: &[&str]) {
    assert!(listed.contains(&wire), "{name} wire value {wire:?} missing from contract list {listed:?}");
}

/// Compile-time + runtime check: every Rust variant has a listed wire name.
pub fn assert_enums_match_lists() {
    for effect in [
        PolicyEffect::Confirm,
        PolicyEffect::Block,
        PolicyEffect::Allow,
        PolicyEffect::PreferEntity,
        PolicyEffect::PreferArea,
        PolicyEffect::Reply,
        PolicyEffect::Script,
        PolicyEffect::Template,
        PolicyEffect::Llm,
    ] {
        let wire = serde_json::to_value(effect).unwrap();
        assert_listed("PolicyEffect", wire.as_str().unwrap(), policy_effects());
        match effect {
            PolicyEffect::Confirm
            | PolicyEffect::Block
            | PolicyEffect::Allow
            | PolicyEffect::PreferEntity
            | PolicyEffect::PreferArea
            | PolicyEffect::Reply
            | PolicyEffect::Script
            | PolicyEffect::Template
            | PolicyEffect::Llm => {}
        }
    }

    for band in [RefineBand::Status, RefineBand::Command, RefineBand::Prompt, RefineBand::Reject] {
        let wire = serde_json::to_value(band).unwrap();
        assert_listed("RefineBand", wire.as_str().unwrap(), refine_bands());
        match band {
            RefineBand::Status | RefineBand::Command | RefineBand::Prompt | RefineBand::Reject => {}
        }
    }

    for reason in [
        RejectReason::EmptyInput,
        RejectReason::InvalidInput,
        RejectReason::NoAction,
        RejectReason::OutOfDomain,
        RejectReason::NoTarget,
        RejectReason::Ambiguous,
        RejectReason::Unsafe,
        RejectReason::Unsupported,
    ] {
        let wire = serde_json::to_value(&reason).unwrap();
        assert_listed("RejectReason", wire.as_str().unwrap(), reject_reasons());
        match reason {
            RejectReason::EmptyInput
            | RejectReason::InvalidInput
            | RejectReason::NoAction
            | RejectReason::OutOfDomain
            | RejectReason::NoTarget
            | RejectReason::Ambiguous
            | RejectReason::Unsafe
            | RejectReason::Unsupported => {}
        }
    }

    for personality in [
        Personality::Default,
        Personality::Butler,
        Personality::Locker,
        Personality::Fuersorglich,
        Personality::Party,
        Personality::Grantig,
        Personality::Sarkastisch,
        Personality::Pirat,
        Personality::Hippie,
        Personality::Gollum,
        Personality::Jarvis,
        Personality::Custom,
    ] {
        let wire = serde_json::to_value(personality).unwrap();
        assert_listed("Personality", wire.as_str().unwrap(), personalities());
        match personality {
            Personality::Default
            | Personality::Butler
            | Personality::Locker
            | Personality::Fuersorglich
            | Personality::Party
            | Personality::Grantig
            | Personality::Sarkastisch
            | Personality::Pirat
            | Personality::Hippie
            | Personality::Gollum
            | Personality::Jarvis
            | Personality::Custom => {}
        }
    }

    for mode in [Mode::Full, Mode::ContextOnly] {
        let wire = serde_json::to_value(mode).unwrap();
        assert_listed("Mode", wire.as_str().unwrap(), modes());
        match mode {
            Mode::Full | Mode::ContextOnly => {}
        }
    }

    for unit in [UnitSystem::Metric, UnitSystem::Imperial] {
        let wire = serde_json::to_value(unit).unwrap();
        assert_listed("UnitSystem", wire.as_str().unwrap(), unit_systems());
        match unit {
            UnitSystem::Metric | UnitSystem::Imperial => {}
        }
    }

    for tier in [Tier::Stable, Tier::Experimental] {
        let wire = serde_json::to_value(tier).unwrap();
        assert_listed("Tier", wire.as_str().unwrap(), language_tiers());
        match tier {
            Tier::Stable | Tier::Experimental => {}
        }
    }

    for decision in [
        ParseDecision::Execute,
        ParseDecision::Clarify { prompt: String::new(), options: Vec::new() },
        ParseDecision::Confirm { prompt: String::new(), candidate_id: String::new() },
        ParseDecision::Reject { reason: RejectReason::NoTarget },
        ParseDecision::Chat,
        ParseDecision::Error { code: String::new(), message: String::new() },
    ] {
        let wire = serde_json::to_value(&decision).unwrap();
        let kind = wire.get("type").and_then(|v| v.as_str()).unwrap();
        assert_listed("ParseDecision", kind, parse_decisions());
        match decision {
            ParseDecision::Execute
            | ParseDecision::Clarify { .. }
            | ParseDecision::Confirm { .. }
            | ParseDecision::Reject { .. }
            | ParseDecision::Chat
            | ParseDecision::Error { .. } => {}
        }
    }

    for event in [
        ChatEvent::Delta { text: String::new() },
        ChatEvent::Done { text: String::new() },
        ChatEvent::Error { message: String::new() },
        ChatEvent::Proposal { value: serde_json::Value::Null },
        ChatEvent::Validate { value: serde_json::Value::Null },
        ChatEvent::Consent { call_id: String::new(), tool: String::new(), summary: String::new(), validate: serde_json::Value::Null },
        ChatEvent::Session { yolo: false, allowed: Vec::new() },
        ChatEvent::ToolCall { id: String::new(), name: String::new(), arguments: String::new() },
        ChatEvent::Tool { tool: String::new(), text: None, intent: None, slots: None },
    ] {
        let wire = serde_json::to_value(&event).unwrap();
        let kind = wire.get("type").and_then(|v| v.as_str()).unwrap();
        assert_listed("ChatEvent", kind, chat_event_types());
        match event {
            ChatEvent::Delta { .. }
            | ChatEvent::Done { .. }
            | ChatEvent::Error { .. }
            | ChatEvent::Proposal { .. }
            | ChatEvent::Validate { .. }
            | ChatEvent::Consent { .. }
            | ChatEvent::Session { .. }
            | ChatEvent::ToolCall { .. }
            | ChatEvent::Tool { .. } => {}
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::types::{ParseOutcome, Settings};

    #[test]
    fn rust_enums_match_exported_lists() {
        assert_enums_match_lists();
    }

    #[test]
    fn settings_field_list_covers_serialized_keys() {
        let value = serde_json::to_value(Settings::default()).unwrap();
        let object = value.as_object().unwrap();
        for key in object.keys() {
            assert!(settings_fields().contains(&key.as_str()), "Settings field {key} missing from SETTINGS_FIELDS");
        }
        for field in settings_fields() {
            assert!(object.contains_key(*field), "SETTINGS_FIELDS has {field} but Settings JSON does not");
        }
    }

    #[test]
    fn parse_outcome_field_list_covers_serialized_keys() {
        let mut outcome = ParseOutcome {
            schema_version: PARSE_SCHEMA_VERSION.into(),
            text: "x".into(),
            conversation_id: "c".into(),
            decision: ParseDecision::Chat,
            speech: String::new(),
            confidence: 0.0,
            margin: 0.0,
            selected_candidate_id: Some("id".into()),
            candidates: Vec::new(),
            plan: None,
            evidence: Vec::new(),
            trace: Default::default(),
            briefing: false,
            news_topic: Some("sport".into()),
            retrieval: None,
            policy_trace: None,
            quiet_ack_eligible: false,
            refine_band: Some(RefineBand::Status),
        };
        outcome.enforce_output_caps();
        let value = serde_json::to_value(&outcome).unwrap();
        let object = value.as_object().unwrap();
        for key in object.keys() {
            assert!(parse_outcome_fields().contains(&key.as_str()), "ParseOutcome field {key} missing from PARSE_OUTCOME_FIELDS");
        }
    }

    #[test]
    fn typescript_export_mentions_news_topic_and_time_zone() {
        let ts = export_typescript();
        assert!(ts.contains("\"news_topic\""));
        assert!(ts.contains("\"time_zone\""));
        assert!(ts.contains("MAX_TRACE_TOKEN_CHARS"));
        assert!(ts.contains("LANGUAGE_TIERS"));
        assert!(ts.contains("CHAT_EVENT_TYPES"));
    }

    #[test]
    fn a_new_settings_field_without_list_update_fails_the_coverage_test() {
        // Documents the drift gate: settings_field_list_covers_serialized_keys fails when
        // Settings gains a serde field that is not in settings_fields().
        assert!(settings_fields().contains(&"time_zone"));
    }
}
