import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import {
  LANGUAGE_TIERS,
  MAX_PARSE_CHARS,
  MAX_TRACE_TOKEN_CHARS,
  PARSE_OUTCOME_FIELDS,
  PARSE_SCHEMA_VERSION,
  POLICY_EFFECTS,
  REFINE_BANDS,
  REJECT_REASONS,
  SETTINGS_FIELDS,
} from "../src/generated/contract";
import { charCount, parseV2Response } from "../src/parseContract";
import { parseResult } from "./support/fixtures";

describe("charCount (U-27)", () => {
  it("counts Unicode scalars, not UTF-16 code units", () => {
    expect(charCount("😀")).toBe(1);
    expect("😀".length).toBe(2);
    expect(charCount("😀".repeat(40))).toBe(40);
    expect("😀".repeat(40).length).toBe(80);
  });

  it("accepts a text that is under the char cap but over the UTF-16 unit cap", () => {
    const emoji = "😀".repeat(MAX_PARSE_CHARS - 20);
    const text = `turn on the light ${emoji}`;
    expect(charCount(text)).toBeLessThanOrEqual(MAX_PARSE_CHARS);
    expect(text.length).toBeGreaterThan(MAX_PARSE_CHARS);

    const payload = parseResult({
      decision: { type: "chat" },
      speech: "",
    });
    payload.text = text;
    payload.trace = { stages: [], discarded: [], tokens: ["😀".repeat(MAX_TRACE_TOKEN_CHARS)], normalized: "" };
    expect(() => parseV2Response(payload)).not.toThrow();
  });

  it("rejects a token that exceeds the shared Unicode scalar cap", () => {
    const payload = parseResult({ decision: { type: "chat" }, speech: "" });
    payload.trace = { stages: [], discarded: [], tokens: ["😀".repeat(MAX_TRACE_TOKEN_CHARS + 1)], normalized: "" };
    expect(() => parseV2Response(payload)).toThrow(/trace\.tokens\[0\]/);
  });
});

describe("parse contract fields (U-35)", () => {
  it("accepts news_topic on a briefing response", () => {
    const payload = parseResult({ decision: { type: "chat" }, speech: "Here is the sport news." });
    (payload as { news_topic?: string; briefing: boolean }).news_topic = "sport";
    payload.briefing = true;
    expect(() => parseV2Response(payload)).not.toThrow();
    expect(PARSE_OUTCOME_FIELDS).toContain("news_topic");
  });

  it("rejects an unknown reject reason (closed enum)", () => {
    const payload = parseResult({ decision: { type: "reject", reason: "no_match" }, speech: "no" });
    expect(() => parseV2Response(payload)).toThrow(/reject reason/);
  });

  it("lists every settings and parse field the UI contract tracks", () => {
    expect(SETTINGS_FIELDS).toContain("time_zone");
    expect(REFINE_BANDS).toEqual(["status", "command", "prompt", "reject"]);
    expect(POLICY_EFFECTS.length).toBe(9);
    expect(REJECT_REASONS).toContain("no_target");
    expect(LANGUAGE_TIERS).toEqual(["reference", "beta", "experimental"]);
    expect(PARSE_SCHEMA_VERSION).toBe("2.0");
  });
});

describe("generated contract drift gate", () => {
  it("ships a generated file that the exporter owns", () => {
    const path = resolve(__dirname, "../src/generated/contract.ts");
    const body = readFileSync(path, "utf8");
    expect(body.startsWith("// @generated by cargo run --bin export_web_contract")).toBe(true);
    expect(body).toContain("SETTINGS_FIELDS");
    expect(body).toContain("\"time_zone\"");
    expect(body).toContain("\"news_topic\"");
  });
});
